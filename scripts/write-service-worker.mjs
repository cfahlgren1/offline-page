// Writes dist/sw.js, which saves every built file on the first visit and serves them from the cache afterwards.
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const dist = new URL("../dist/", import.meta.url).pathname;

function listFiles(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    return statSync(path).isDirectory() ? listFiles(path) : [path];
  });
}

const files = listFiles(dist)
  .map((path) => relative(dist, path))
  .filter((path) => path !== "sw.js" && !path.endsWith(".DS_Store"))
  .sort();

// The cache name changes whenever any file does, so a new deploy replaces the old cache in one step.
const hash = createHash("sha256");
for (const file of files) hash.update(file).update(readFileSync(join(dist, file)));
const version = hash.digest("hex").slice(0, 12);

const worker = `// Generated by scripts/write-service-worker.mjs. Do not edit.
const CACHE = "offline-page-${version}";
const FILES = ${JSON.stringify(files.map((file) => `./${file}`), null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) => Promise.all(names.filter((name) => name.startsWith("offline-page-") && name !== CACHE).map((name) => caches.delete(name))))
      .then(() => self.clients.claim()),
  );
});

// Cache first: every file is versioned by the cache name, so the cached copy is always the right one.
// ignoreVary, because module scripts are requested with an Origin header that the cached copies weren't.
// Page loads get index.html: hosts like HF Spaces answer "/" with a redirect, and a redirected response can't be served for a navigation.
const MATCH = { ignoreSearch: true, ignoreVary: true };

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  const lookup = caches.match(request.mode === "navigate" ? "./index.html" : request, MATCH);
  event.respondWith(lookup.then((cached) => cached ?? fetch(request)));
});
`;

writeFileSync(join(dist, "sw.js"), worker);
console.log(`sw.js: ${files.length} files cached as offline-page-${version}`);
